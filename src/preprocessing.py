"""
Data preprocessing pipeline module for House Price Regression.
Builds ColumnTransformer and Pipelines using SimpleImputer, StandardScaler, and OneHotEncoder.
Guaranteed to fit parameters strictly on training splits to prevent data leakage.
"""

from typing import List, Tuple
import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

from src.config import NUMERICAL_FEATURES, CATEGORICAL_FEATURES


# List of engineered feature names generated by engineer_features
ENGINEERED_NUMERICAL_FEATURES: List[str] = [
    "house_age",
    "is_renovated",
    "years_since_renovation",
    "total_rooms",
    "sqft_per_bedroom",
    "sqft_per_bathroom",
    "living_to_lot_ratio",
    "distance_to_center_km",
]


def get_all_numerical_features() -> List[str]:
    """Returns combined list of raw numerical features and engineered numerical features."""
    return NUMERICAL_FEATURES + ENGINEERED_NUMERICAL_FEATURES


def build_preprocessor(
    num_features: List[str] = None,
    cat_features: List[str] = None
) -> ColumnTransformer:
    """
    Constructs a ColumnTransformer for preprocessing housing features.

    Numerical pipeline:
    1. SimpleImputer(strategy='median')
    2. StandardScaler()

    Categorical pipeline:
    1. SimpleImputer(strategy='most_frequent')
    2. OneHotEncoder(handle_unknown='ignore', sparse_output=False)

    Args:
        num_features: List of numerical column names. Defaults to get_all_numerical_features().
        cat_features: List of categorical column names. Defaults to CATEGORICAL_FEATURES.

    Returns:
        ColumnTransformer: Configured preprocessor.
    """
    if num_features is None:
        num_features = get_all_numerical_features()
    if cat_features is None:
        cat_features = CATEGORICAL_FEATURES

    numerical_pipeline = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median")),
            ("scaler", StandardScaler()),
        ]
    )

    categorical_pipeline = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="most_frequent")),
            ("encoder", OneHotEncoder(handle_unknown="ignore", sparse_output=False)),
        ]
    )

    preprocessor = ColumnTransformer(
        transformers=[
            ("num", numerical_pipeline, num_features),
            ("cat", categorical_pipeline, cat_features),
        ],
        remainder="drop",
    )

    return preprocessor


def get_feature_names_out(preprocessor: ColumnTransformer) -> List[str]:
    """
    Extracts output feature names after preprocessor has been fitted.

    Args:
        preprocessor: Fitted ColumnTransformer.

    Returns:
        List[str]: Clean list of output feature names.
    """
    try:
        feature_names = preprocessor.get_feature_names_out()
        clean_names = [
            f.replace("num__", "").replace("cat__", "") for f in feature_names
        ]
        return clean_names
    except Exception:
        return []
